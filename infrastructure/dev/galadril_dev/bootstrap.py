class State(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)
    version: int = 1
    project: str
    origin: str
    openai_configured: bool


def mapping(value: object) -> dict[str, object]:
    if not isinstance(value, dict):
        raise BootstrapError("Expected a configuration mapping")
    return cast(dict[str, object], value)


def records(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        raise BootstrapError("Expected configuration records")
    return [mapping(item) for item in value]


def environment_text(values: dict[str, str]) -> bytes:
    return (
        "# Generated by Galadril development CLI. Never commit this file.\n"
        + "\n".join(
            f"{key}={json.dumps(value, ensure_ascii=False)}"
            for key, value in sorted(values.items())
        )
        + "\n"
    ).encode()


def parse_environment(path: Path) -> dict[str, str]:
    values = dotenv_values(
        stream=StringIO(read(path).decode()), interpolate=False
    )
    if any(value is None for value in values.values()):
        raise BootstrapError("Every dotenv setting must have an explicit value")
    return {key: value for key, value in values.items() if value is not None}


class Bootstrap:
    """Own only .local/dev; legacy data is never deleted or silently rotated."""

    __slots__ = ("root", "state")

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()
        self.state = self.root / ".local/dev"

    async def initialize(
        self,
        *,
        import_env: Path | None = None,
        openai_key: SecretStr | None = None,
    ) -> State:
        try:
            return await asyncio.to_thread(
                self._initialize, import_env, openai_key
            )
        except (OSError, ValueError, yaml.YAMLError) as error:
            raise BootstrapError(
                f"Development initialization failed ({type(error).__name__})"
            ) from None

    def _initialize(
        self, imported: Path | None, openai_key: SecretStr | None
    ) -> State:
        private_directory(self.root / ".local")
        private_directory(self.state)
        with locked(self.state / ".initialize.lock"):
            return self._prepare(imported, openai_key)

    def _prepare(
        self, imported: Path | None, openai_key: SecretStr | None
    ) -> State:
        env_path = self.state / "compose.env"
        managed = (
            env_path if env_path.exists() or env_path.is_symlink() else None
        )
        previous = imported if imported is not None else managed
        example = self.root / "infrastructure/docker/.env.example"
        defaults = parse_environment(example)
        env = defaults.copy()
        preserved = parse_environment(managed) if managed else {}
        incoming = parse_environment(previous) if previous else {}
        if previous is not None and previous != env_path:
            # Old Compose supplied these defaults when no value was stored in dotenv.
            for name in (
                "POSTGRES_PASSWORD",
                "MINIO_ROOT_PASSWORD",
                "GALADRIL_APP_PASSWORD",
                "GALADRIL_MAINTENANCE_PASSWORD",
                "SPICEDB_GRPC_PRESHARED_KEY",
                "LAKEFS_SECRET_ACCESS_KEY",
                "LAKEFS_AUTH_ENCRYPT_SECRET_KEY",
            ):
                if not incoming.get(name) and defaults.get(name):
                    incoming[name] = defaults[name]
        preserved.update(incoming)
        env.update(preserved)
        for name in SECRET_NAMES:
            if preserved.get(name):
                continue
            if name == "SCRIBE_CHATGPT_ENCRYPTION_KEY":
                env[name] = base64.urlsafe_b64encode(
                    secrets.token_bytes(32)
                ).decode()
            elif name in {"POLIS_ENCRYPTION_KEY", "KRATOS_CIPHER_SECRET"}:
                env[name] = secrets.token_hex(16)
            else:
                env[name] = secrets.token_hex(32)
        if openai_key is not None:
            env["SCRIBE_OPENAI_API_KEY"] = openai_key.get_secret_value()
        env.setdefault("SCRIBE_OPENAI_API_KEY", "")
        self._models(env)
        env["COMPOSE_PROJECT_NAME"] = preserved.get(
            "COMPOSE_PROJECT_NAME", "galadril-dev"
        )
        env["GALADRIL_PROXY_UID"] = preserved.get("GALADRIL_PROXY_UID") or str(
            os.getuid()
        )
        env["GALADRIL_PROXY_GID"] = preserved.get("GALADRIL_PROXY_GID") or str(
            os.getgid()
        )
        if (
            re.fullmatch(
                r"[a-z0-9][a-z0-9_-]{0,62}", env["COMPOSE_PROJECT_NAME"]
            )
            is None
        ):
            raise BootstrapError("Invalid Compose project name")
        env.update(
            {
                "AUTH_PUBLIC_ORIGIN": "https://localhost:8080",
                "AUTH_LOCAL_LOGIN_ENABLED": "true",
                "COMPOSE_PROFILES": "local-auth,document-compiler",
                "GALADRIL_IDENTITY_DIR": str(self.state / "identity"),
                "GALADRIL_PUBLIC_TLS_DIR": str(self.state / "identity/gateway"),
                "GALADRIL_CONNECTORS_PATH": str(self.state / "connectors.yaml"),
                "DOCUMENT_COMPILER_BUNDLE_DIRECTORY": str(
                    self.state / "document-compiler/bundle"
                ),
                "DOCUMENT_COMPILER_S3_BUCKET": "galadril-document-compiler",
            }
        )
        env.setdefault(
            "DOCUMENT_COMPILER_S3_ACCESS_KEY",
            "compiler-" + secrets.token_hex(10),
        )
        env.setdefault(
            "GALADRIL_DOCUMENT_COMPILER_IMAGE",
            "ghcr.io/aeluin-technologies/galadril-document-compiler:latest",
        )
        env.setdefault(
            "GALADRIL_DOCUMENT_WORKER_IMAGE",
            "ghcr.io/aeluin-technologies/galadril-document-worker:latest",
        )
        env.setdefault("DOCUMENT_COMPILER_BUNDLE_SHA256", "0" * 64)
        self._adopt_identity(preserved)
        certificates(self.state / "identity")
        revision = hashlib.sha256()
        for public in sorted((self.state / "identity").rglob("cert.pem")):
            revision.update(read(public))
        revision.update(read(self.state / "identity/ca.pem"))
        env["GALADRIL_TLS_REVISION"] = revision.hexdigest()
        signer = self.state / "jwt"
        if not signer.exists():
            initialize(signer)
        else:
            private_directory(signer)
            read(signer / "signing-key.pem")
            read(signer / "jwks.json")
        self._utils(env, preserved)
        self._connectors(env)
        self._envoy()
        self._compose()
        self._storage_policy(env)
        private_directory(self.state / "document-compiler/bundle")
        write(env_path, environment_text(env))
        if not (self.state / "token.jwt").exists():
            self.token("local-developer", "local-development")
        state = State(
            project=env["COMPOSE_PROJECT_NAME"],
            origin=env["AUTH_PUBLIC_ORIGIN"],
            openai_configured=bool(env["SCRIBE_OPENAI_API_KEY"]),
        )
        write(
            self.state / "state.json",
            state.model_dump_json(indent=2).encode() + b"\n",
        )
        return state

    def environment(self) -> dict[str, str]:
        return parse_environment(self.state / "compose.env")

    def update_environment(self, values: dict[str, str]) -> None:
        env = self.environment()
        env.update(values)
        write(self.state / "compose.env", environment_text(env))

    def token(self, subject: str, tenant: str) -> Path:
        if not subject or not tenant or max(len(subject), len(tenant)) > 128:
            raise BootstrapError(
                "Existing user and tenant identifiers are required"
            )
        destination = self.state / "token.jwt"
        write(
            destination,
            (issue_token(self.state / "jwt", subject, tenant) + "\n").encode(),
        )
        return destination

    def compose_arguments(self) -> tuple[str, ...]:
        return (
            "docker",
            "compose",
            "--project-directory",
            str(self.root / "infrastructure/docker"),
            "--env-file",
            str(self.state / "compose.env"),
            "-f",
            str(self.root / "infrastructure/docker/docker-compose.yaml"),
            "-f",
            str(self.root / "infrastructure/docker/document-compiler.yaml"),
            "-f",
            str(self.state / "compose.yaml"),
            "--profile",
            "local-auth",
            "--profile",
            "document-compiler",
        )

    def _adopt_identity(self, preserved: dict[str, str]) -> None:
        target = self.state / "identity"
        if target.exists():
            return
        source = Path(
            preserved.get(
                "GALADRIL_IDENTITY_DIR", str(self.root / ".local/identity")
            )
        )
        if not source.is_absolute():
            source = self.root / "infrastructure/docker" / source
        if source.is_symlink():
            raise BootstrapError(
                "The existing identity directory must not be symlinked"
            )
        if not (source / "ca-key.pem").is_file():
            return
        private_directory(target)
        for name in ("ca-key.pem", "ca.pem"):
            write(target / name, read(source / name), public=name == "ca.pem")
        for workload in WORKLOADS:
            old = source / workload
            if old.is_symlink():
                raise BootstrapError(
                    "The existing workload directory must not be symlinked"
                )
            if old.is_dir():
                for name in ("key.pem", "cert.pem", "ca.pem"):
                    if (old / name).is_file():
                        write(
                            target / workload / name,
                            read(old / name),
                            public=name != "key.pem",
                        )

    def _utils(self, env: dict[str, str], preserved: dict[str, str]) -> None:
        root = self.state / "utils-email"
        for name in ("private", "data"):
            private_directory(root / name)
        for name in ("service-key", "tracking-key"):
            target = root / "private" / name
            if not target.exists():
                write(target, secrets.token_hex(32).encode() + b"\n")
            else:
                read(target)
        keyring = root / "private/keyring.json"
        if not keyring.exists():
            write(
                keyring,
                json.dumps(
                    {
                        "active": "v1",
                        "keys": {
                            "v1": base64.b64encode(
                                secrets.token_bytes(32)
                            ).decode()
                        },
                    }
                ).encode()
                + b"\n",
            )
        uid = os.getuid() if hasattr(os, "getuid") else 1000
        gid = os.getgid() if hasattr(os, "getgid") else 1000
        if uid == 0:
            uid = gid = 1000
            for target in (root, *root.rglob("*")):
                os.chown(target, uid, gid)
        for key, value in {
            "GALADRIL_UTILS_PRIVATE_DIR": str(root / "private"),
            "GALADRIL_UTILS_DATA_DIR": str(root / "data"),
            "GALADRIL_UTILS_UID": str(uid),
            "GALADRIL_UTILS_GID": str(gid),
        }.items():
            env[key] = preserved.get(key) or value

    def _models(self, env: dict[str, str]) -> None:
        """Select managed defaults without relying on an included project's legacy dotenv."""
        catalogs = mapping(
            json.loads(
                read(
                    Path(__file__).resolve().parent.parent
                    / "model-catalogs.json"
                )
            )
        )
        previous = catalogs.get(env.get("GALADRIL_DEV_MODEL_CATALOG", ""))
        configured = env.get("SCRIBE_MODELS")
        owned = (
            isinstance(previous, dict)
            and configured is not None
            and json.loads(configured) == previous.get("models")
            and env.get("SCRIBE_DEFAULT_MODEL") == previous.get("default_model")
        )
        if configured and not owned:
            return
        selected = "openai" if env["SCRIBE_OPENAI_API_KEY"] else "unconfigured"
        catalog = mapping(catalogs[selected])
        models = mapping(catalog["models"])
        default = catalog["default_model"]
        if not isinstance(default, str) or (models and default not in models):
            raise BootstrapError("Invalid managed model catalog")
        env["SCRIBE_MODELS"] = json.dumps(models, separators=(",", ":"))
        env["SCRIBE_DEFAULT_MODEL"] = default
        env["GALADRIL_DEV_MODEL_CATALOG"] = selected

    def _connectors(self, env: dict[str, str]) -> None:
        config = mapping(
            yaml.safe_load(
                read(self.root / "infrastructure/docker/connectors.yaml")
            )
        )
        connectors = mapping(config["connectors"])
        mapping(connectors["s3"]).update(
            access_key=env["MINIO_ROOT_USER"],
            secret_key=env["MINIO_ROOT_PASSWORD"],
        )
        mapping(connectors["postgres"]).update(
            password=env["GALADRIL_APP_PASSWORD"],
            maintenance_password=env["GALADRIL_MAINTENANCE_PASSWORD"],
            database=env["POSTGRES_DB"],
        )
        mapping(connectors["spicedb"])["token"] = env[
            "SPICEDB_GRPC_PRESHARED_KEY"
        ]
        write(
            self.state / "connectors.yaml",
            yaml.safe_dump(config, sort_keys=False).encode(),
        )

    def _envoy(self) -> None:
        config = mapping(
            yaml.safe_load(read(self.root / "infrastructure/envoy/local.yaml"))
        )
        resources = mapping(config["static_resources"])
        jwks = read(self.state / "jwt/jwks.json").decode()
        for listener in records(resources["listeners"]):
            for chain in records(listener.get("filter_chains", [])):
                for network_filter in records(chain["filters"]):
                    manager = mapping(network_filter["typed_config"])
                    for item in records(manager.get("http_filters", [])):
                        if item.get("name") != "envoy.filters.http.jwt_authn":
                            continue
                        auth = mapping(item["typed_config"])
                        providers = mapping(auth["providers"])
                        provider = copy.deepcopy(mapping(providers["identity"]))
                        del provider["remote_jwks"]
                        provider["local_jwks"] = {"inline_string": jwks}
                        providers["local_development"] = provider
                        for rule in records(auth["rules"]):
                            rule["requires"] = {
                                "requires_any": {
                                    "requirements": [
                                        {"provider_name": "identity"},
                                        {"provider_name": "local_development"},
                                    ]
                                }
                            }
        write(
            self.state / "envoy.yaml",
            yaml.safe_dump(config, sort_keys=False).encode(),
        )

    def _compose(self) -> None:
        def bind(source: Path, target: str) -> dict[str, object]:
            return {
                "type": "bind",
                "source": str(source),
                "target": target,
                "read_only": True,
                "bind": {"create_host_path": False},
            }

        overlay = {
            "services": {
                "api-proxy": {
                    "volumes": [
                        bind(self.state / "envoy.yaml", "/etc/envoy/envoy.yaml")
                    ]
                },
                "scribe": {
                    "environment": {
                        "SCRIBE_OPENAI_API_KEY": "${SCRIBE_OPENAI_API_KEY:-}"
                    }
                },
                "document-compiler": {
                    "depends_on": {
                        "document-storage-init": {
                            "condition": "service_completed_successfully"
                        }
                    }
                },
                "document-storage-init": {
                    "profiles": ["document-compiler"],
                    "image": "${MINIO_CLIENT_IMAGE:-bitnamilegacy/minio-client:2025.7.21-debian-12-r3@sha256:73bd39f7899a0cef12b8dd5df13aa93a3ed1aaa44236542442e9ac76819ac158}",
                    "restart": "no",
                    "read_only": True,
                    "cap_drop": ["ALL"],
                    "security_opt": ["no-new-privileges:true"],
                    "tmpfs": ["/tmp:size=16m,mode=1777"],
                    "environment": {
                        key: "${" + key + "}"
                        for key in (
                            "MINIO_ROOT_USER",
                            "MINIO_ROOT_PASSWORD",
                            "DOCUMENT_COMPILER_S3_ACCESS_KEY",
                            "DOCUMENT_COMPILER_S3_SECRET_KEY",
                            "DOCUMENT_COMPILER_S3_BUCKET",
                        )
                    },
                    "depends_on": {"rustfs": {"condition": "service_healthy"}},
                    "entrypoint": ["/bin/sh", "/bootstrap/storage.sh"],
                    "volumes": [
                        bind(
                            Path(__file__).resolve().parent.parent
                            / "storage.sh",
                            "/bootstrap/storage.sh",
                        ),
                        bind(
                            self.state / "compiler-policy.json",
                            "/bootstrap/policy.json",
                        ),
                        bind(
                            self.state / "compiler-lifecycle.json",
                            "/bootstrap/lifecycle.json",
                        ),
                    ],
                },
            }
        }
        services = mapping(overlay["services"])
        for name in (
            "api-proxy",
            "gateway",
            "registry",
            "intake",
            "vision",
            "scribe",
            "hydra",
            "polis",
            "kratos",
            "studio",
        ):
            service = services.setdefault(name, {})
            mapping(service)["labels"] = {
                "galadril.dev/tls-revision": "${GALADRIL_TLS_REVISION}"
            }
        write(
            self.state / "compose.yaml",
            yaml.safe_dump(overlay, sort_keys=False).encode(),
        )

    def _storage_policy(self, env: dict[str, str]) -> None:
        bucket = env["DOCUMENT_COMPILER_S3_BUCKET"]
        policy = {
            "Version": "2012-10-17",
            "Statement": [
                {
                    "Effect": "Allow",
                    "Action": [
                        "s3:ListBucket",
                        "s3:ListBucketVersions",
                        "s3:GetBucketLocation",
                    ],
                    "Resource": [f"arn:aws:s3:::{bucket}"],
                },
                {
                    "Effect": "Allow",
                    "Action": [
                        "s3:GetObject",
                        "s3:PutObject",
                        "s3:DeleteObject",
                        "s3:GetObjectVersion",
                        "s3:DeleteObjectVersion",
                        "s3:PutObjectTagging",
                        "s3:GetObjectTagging",
                    ],
                    "Resource": [f"arn:aws:s3:::{bucket}/*"],
                },
            ],
        }
        lifecycle = {
            "Rules": [
                {
                    "ID": "generated-seven-days",
                    "Status": "Enabled",
                    "Filter": {
                        "Tag": {
                            "Key": "galadril-retention",
                            "Value": "seven-days",
                        }
                    },
                    "Expiration": {"Days": 7},
                    "NoncurrentVersionExpiration": {"NoncurrentDays": 7},
                },
                {
                    "ID": "expired-delete-markers",
                    "Status": "Enabled",
                    "Filter": {"Prefix": ""},
                    "Expiration": {"ExpiredObjectDeleteMarker": True},
                },
            ]
        }
        write(
            self.state / "compiler-policy.json",
            json.dumps(policy, indent=2).encode() + b"\n",
        )
        write(
            self.state / "compiler-lifecycle.json",
            json.dumps(lifecycle, indent=2).encode() + b"\n",
        )
